// 1.0.0 asset guard through the real extension UI: a 546 sat Taproot coin shows as Protected,
// is left out of automatic sends and Max, and can be unlocked by hand after the warning.
import { launch } from "./harness.mjs";
import { backupChecks, screens } from "./paths.mjs";
const OUT = screens("assets");
import { mkdirSync } from "node:fs";
mkdirSync(OUT, { recursive: true });
const h = await launch({ out: OUT });
const { send, hook, open, page, pop, ok, capture, settle, click, text } = h;
const ob = await send({ type: "NEW_MNEMONIC" });
await send({ type: "CREATE_CHECKED", password: "throwaway-assets", name: "Daily", checks: backupChecks(ob.mnemonic) });
await send({ type: "PREFS_SET", prefs: { priceSource: "off" } });
await hook(() => self.__pbE2E.fundOpenWallet("200000"));
const small = await hook(() => self.__pbE2E.fundOpenWallet("546"));
const op = `${small}:0`;
let coins = await send({ type: "COINS" });
ok("546 sat Taproot coin is protected", coins.find((c) => c.outpoint === op)?.status === "protected");
const st = await send({ type: "STATE" }).catch(() => null);
if (st?.balance !== undefined) ok("balance leaves the protected coin out", st.balance === "200000", st.balance);
const max = await send({ type: "MAX_AMOUNT", feeRate: 1 }).catch((e) => ({ err: e.message }));
if (!max.err) ok("Max leaves the protected coin out", BigInt(max.amount) + BigInt(max.fee) === 200000n, JSON.stringify(max));
await open(page, "coins");
ok("Coins list says Protected, may hold an asset", (await text()).includes("Protected, may hold an asset"));
await capture("coins-protected", (p) => open(p, "coins"), { widths: [375, 1280] });
await capture("coin-protected-detail", (p) => open(p, "coin-detail", { op }), { widths: [375, 1280] });
await open(page, "coin-detail", { op });
ok("Unlock waits for the warning box", await page.locator('[data-act="coin-asset-unlock"]').isDisabled());
await page.locator('input[data-f="assetAck"]').check();
await settle(page, 300);
await click('[data-act="coin-asset-unlock"]');
await settle(page, 800);
coins = await send({ type: "COINS" });
ok("after the hand unlock the coin is spendable", coins.find((c) => c.outpoint === op)?.status === "private");
await open(page, "coin-detail", { op });
ok("an unlocked coin offers Protect it again", (await text()).includes("Protect it again"));
await click('[data-act="coin-asset-protect"]');
coins = await send({ type: "COINS" });
ok("protect again works", coins.find((c) => c.outpoint === op)?.status === "protected");
const asset = await send({ type: "SET_COIN_META", outpoint: op, patch: { asset: "none" } });
ok("the page cannot mark a coin as checked", asset.find((c) => c.outpoint === op)?.status === "protected");
void pop;
await h.finish();
